package com.driss.puzzles.ui

fun formatDuration(ms: Long): String {
    val total = ms / 1000
    val h = total / 3600
    val m = (total % 3600) / 60
    val s = total % 60
    return if (h > 0) "%d:%02d:%02d".format(h, m, s) else "%d:%02d".format(m, s)
}

fun categoryLabel(category: String?): String =
    category?.replaceFirstChar { it.uppercase() } ?: "My photos"
